#!/usr/bin/env python3
"""Generates Sources/MeridianUI/Icons/MRIconData.swift from the canvas' icons.svg sprite.

usage: gen_icons.py path/to/icons.svg > Sources/MeridianUI/Icons/MRIconData.swift
Every primitive (circle, ellipse, rect) is converted to a path string; the runtime only needs SVGPath.parse.
"""
import re
import sys
import xml.etree.ElementTree as ET

NS = "{http://www.w3.org/2000/svg}"


def f(x):
    return ("%.4f" % float(x)).rstrip("0").rstrip(".")


def circle(cx, cy, rx, ry):
    cx, cy, rx, ry = map(float, (cx, cy, rx, ry))
    return f"M{f(cx - rx)} {f(cy)}A{f(rx)} {f(ry)} 0 1 0 {f(cx + rx)} {f(cy)}A{f(rx)} {f(ry)} 0 1 0 {f(cx - rx)} {f(cy)}Z"


def rect(x, y, w, h, rx, ry):
    x, y, w, h = map(float, (x, y, w, h))
    rx = float(rx or ry or 0)
    ry = float(ry or rx or 0)
    rx, ry = min(rx, w / 2), min(ry, h / 2)
    if rx == 0 and ry == 0:
        return f"M{f(x)} {f(y)}H{f(x + w)}V{f(y + h)}H{f(x)}Z"
    return (f"M{f(x + rx)} {f(y)}H{f(x + w - rx)}A{f(rx)} {f(ry)} 0 0 1 {f(x + w)} {f(y + ry)}"
            f"V{f(y + h - ry)}A{f(rx)} {f(ry)} 0 0 1 {f(x + w - rx)} {f(y + h)}H{f(x + rx)}"
            f"A{f(rx)} {f(ry)} 0 0 1 {f(x)} {f(y + h - ry)}V{f(y + ry)}A{f(rx)} {f(ry)} 0 0 1 {f(x + rx)} {f(y)}Z")


def parts(el, inherited_fill):
    out = []
    fill = el.get("fill", inherited_fill)
    tag = el.tag.replace(NS, "")
    d = None
    if tag == "path":
        d = el.get("d")
    elif tag == "circle":
        r = el.get("r")
        d = circle(el.get("cx"), el.get("cy"), r, r)
    elif tag == "ellipse":
        d = circle(el.get("cx"), el.get("cy"), el.get("rx"), el.get("ry"))
    elif tag == "rect":
        d = rect(el.get("x", 0), el.get("y", 0), el.get("width"), el.get("height"), el.get("rx"), el.get("ry"))
    if d is not None:
        out.append((d, fill == "currentColor"))
    for child in el:
        out.extend(parts(child, fill))
    return out


RENAMES = {"case": "briefcase"}  # Swift keywords


def camel(name):
    if name in RENAMES:
        return RENAMES[name]
    p = name.split("-")
    return p[0] + "".join(x.capitalize() for x in p[1:])


def main():
    root = ET.parse(sys.argv[1]).getroot()
    syms = [s for s in root.iter(NS + "symbol")]
    print("// Generated by Scripts/gen_icons.py from the canvas' icons.svg. Do not edit by hand.")
    print("// Sprite: 24x24 viewBox, 1.5 stroke, round caps/joins, currentColor.\n")
    print("public enum MRIconName: String, CaseIterable, Sendable {")
    for s in syms:
        i = s.get("id")
        print(f'    case {camel(i)}' + (f' = "{i}"' if camel(i) != i else ""))
    print("}\n")
    print("/// One drawable primitive of an icon: SVG path data and whether it is filled (true) or stroked (false).")
    print("struct MRIconPart: Sendable { let d: String; let filled: Bool }\n")
    print("enum MRIconData {")
    print("    static let parts: [MRIconName: [MRIconPart]] = [")
    for s in syms:
        i = s.get("id")
        ps = []
        for child in s:
            ps.extend(parts(child, "none"))
        body = ", ".join(f'MRIconPart(d: "{d}", filled: {"true" if fl else "false"})' for d, fl in ps)
        print(f"        .{camel(i)}: [{body}],")
    print("    ]\n}")


main()
